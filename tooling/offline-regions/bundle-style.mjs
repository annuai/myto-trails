#!/usr/bin/env node
// Bundles the OpenFreeMap "liberty" and "dark" styles for offline maps (laptop only; rerun only when the style should change).
//
// Usage: node tooling/offline-regions/bundle-style.mjs
//
// Fetches only public files from tiles.openfreemap.org (free, no key): the style JSONs, their sprite
// (1x and 2x, shared) and the glyph ranges of the font stacks the styles use: Latin, Latin extended and punctuation
// (0-511, 7680-7935, 8192-8447) plus the Indic blocks (2304-3583). A range OpenFreeMap has no file for (404 or empty) is skipped.
// Writes apps/mobile/assets/offline-map/{liberty.json, dark.json, sprite/, fonts/, assets.ts}. Offline map tiles are built
// with Planetiler's OpenMapTiles profile, the same schema as OpenFreeMap, so the style works with only its tile source swapped.
import { mkdir, writeFile, readdir, stat, rm } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HOST = 'https://tiles.openfreemap.org';
const OUT = join(dirname(fileURLToPath(import.meta.url)), '../../apps/mobile/assets/offline-map');
const STYLES = ['liberty', 'dark'];
const RANGES = ['0-255', '256-511', '2304-2559', '2560-2815', '2816-3071', '3072-3327', '3328-3583', '7680-7935', '8192-8447'];
const SPRITES = ['sprite.json', 'sprite.png', 'sprite@2x.json', 'sprite@2x.png'];

const get = async (url) => {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return Buffer.from(await res.arrayBuffer());
};
/** Like `get` but null for a missing or empty file (a font stack has no glyphs in some ranges); any other failure throws. */
const getOptional = async (url) => {
  const res = await fetch(url);
  if (res.status === 404) return null;
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  const data = Buffer.from(await res.arrayBuffer());
  return data.length === 0 ? null : data;
};
const put = async (path, data) => {
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, data);
};

const styles = {};
const fonts = new Set();
let spriteBase;
for (const name of STYLES) {
  const style = JSON.parse((await get(`${HOST}/styles/${name}`)).toString('utf8'));
  if (!style.sprite?.startsWith(HOST) || !style.glyphs?.startsWith(HOST)) throw new Error(`unexpected ${name} style shape`);
  if (spriteBase && spriteBase !== style.sprite) throw new Error(`the ${name} style uses a different sprite than the others`);
  spriteBase = style.sprite;
  for (const l of style.layers) for (const f of l.layout?.['text-font'] ?? []) fonts.add(f);
  styles[name] = style;
}
if (fonts.size === 0) throw new Error('no fonts found in the styles');

await rm(OUT, { recursive: true, force: true });
for (const [name, style] of Object.entries(styles)) await put(join(OUT, `${name}.json`), JSON.stringify(style));

// The sprite URL has no extension; MapLibre appends .json/.png (and @2x).
// Metro reads `name@2x.png` as a scaled variant of `name.png` and cannot require it on its own, so the 2x image is stored as `sprite-2x.png`
// and copied back to its `sprite@2x.png` name on the phone (assets.ts maps the two).
const spriteFile = (name) => name.replace('@2x.png', '-2x.png');
for (const name of SPRITES) await put(join(OUT, 'sprite', spriteFile(name)), await get(`${spriteBase}${name.slice('sprite'.length)}`));

const assets = [];
for (const font of fonts) for (const range of RANGES) {
  const rel = `fonts/${font}/${range}.pbf`;
  const data = await getOptional(`${HOST}/fonts/${encodeURIComponent(font)}/${range}.pbf`);
  if (!data) { console.log(`skipped (no glyphs): ${rel}`); continue; }
  await put(join(OUT, rel), data);
  assets.push([rel, rel]);
}
for (const name of SPRITES) assets.push([`sprite/${name}`, `sprite/${spriteFile(name)}`]);

// Metro needs a literal require per file; the app copies them into the document directory (offlineAssets.ts).
const lines = assets.map(([dest, file]) => `  ['${dest}', require('./${file}')],`);
await put(join(OUT, 'assets.ts'), `// Generated by tooling/offline-regions/bundle-style.mjs; do not edit.\nexport const OFFLINE_MAP_ASSETS: [string, number][] = [\n${lines.join('\n')}\n];\n`);

let total = 0;
const walk = async (d) => { for (const e of await readdir(d)) { const p = join(d, e); const s = await stat(p); if (s.isDirectory()) await walk(p); else total += s.size; } };
await walk(OUT);
console.log(`fonts: ${[...fonts].join(', ')}\nfiles: ${assets.length + STYLES.length}, total ${(total / 1024).toFixed(0)} KB`);
if (total > 6 * 1024 * 1024) { console.error('Over the 6 MB budget: drop rarely used fonts.'); process.exit(1); }
