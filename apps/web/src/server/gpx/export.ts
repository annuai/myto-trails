import { canDownloadGpx, isValidSlug } from "@moto-trails/domain";
import type { Sql } from "postgres";
import { getSql, withPublicRole } from "../db/client";
import { queryTrailBySlug } from "../queries/trails.sql";
import type { StorageProvider } from "../storage";
import { parseGpx } from "./parse";
import { writeGpx } from "./write";

export type GpxExportResult =
  | { ok: true; filename: string; xml: string }
  | { ok: false; reason: "not_found" | "no_gpx" | "sensitive_area" | "access_not_allowed" | "permanently_closed" | "not_published" | "unavailable" };

const sentence = (v: string) => {
  const s = v.replaceAll("_", " ");
  return s.charAt(0).toUpperCase() + s.slice(1);
};
const dateOf = (iso: string) => new Date(iso).toLocaleDateString("en-GB", { day: "numeric", month: "short", year: "numeric", timeZone: "UTC" });

/**
 * The downloadable GPX for a trail (docs/14 §4): decided by canDownloadGpx from public data, then regenerated by our
 * own writer from the stored sanitised copy. The original upload is never served. Callers pass the privileged
 * connection; the public decision runs under the anonymous role.
 */
export async function buildGpxExport(i: { sql?: Sql; storage: StorageProvider; slug: string; now: Date; siteUrl: string }): Promise<GpxExportResult> {
  const sql = i.sql ?? getSql();
  if (!isValidSlug(i.slug)) return { ok: false, reason: "not_found" };
  const trail = await withPublicRole(sql, (tx) => queryTrailBySlug(tx, i.slug, i.now));
  if (!trail) return { ok: false, reason: "not_found" };

  const decision = canDownloadGpx({ lifecycle: "published", accessClass: trail.accessClass, sensitivity: trail.sensitivity, hasGpx: trail.hasGpx, condition: trail.condition });
  if (!decision.allowed) return { ok: false, reason: decision.reason };

  const [file] = await sql`
    select g.id, g.storage_key_sanitised as key
    from trail t
    join route r on r.revision_id = t.published_revision_id
    join gpx_file g on g.route_id = r.id and g.status = 'ready'
    where t.slug = ${i.slug} and t.lifecycle = 'published'
    order by g.created_at desc limit 1`;
  if (!file?.key) return { ok: false, reason: "unavailable" };
  const bytes = await i.storage.get("originals", file.key);
  const parsed = bytes ? parseGpx(new TextDecoder().decode(bytes)) : null;
  if (!parsed?.ok) return { ok: false, reason: "unavailable" };

  const page = `${i.siteUrl}/trails/${i.slug}`;
  const verified = trail.verifiedAt ? ` · Verified ${dateOf(trail.verifiedAt)}${trail.validUntil ? ` (re-check by ${dateOf(trail.validUntil)})` : ""}` : "";
  const description = `Access: ${sentence(trail.accessClass)} · Condition: ${sentence(trail.condition)}${verified} · Read before riding: ${page}`;
  const xml = writeGpx({
    name: trail.name,
    description,
    link: page,
    copyright: "Moto Trails contributors",
    points: parsed.tracks.flat(),
    waypoints: parsed.waypoints,
  });
  await sql`update gpx_file set download_count = download_count + 1 where id = ${file.id}`;
  return { ok: true, filename: `${i.slug}.gpx`, xml };
}
