-- Pull-down quotes on the Dash. The app asks for them through GET /api/v1/quotes on first open and then at most once a week, keeps them on the
-- phone, and falls back to the lines bundled in the app until it has them. To add a quote, insert a row; to retire one, set published = false.
-- Closed to the public roles like the other tables: the application reads them through the API.

create table ride_quote (
  id integer generated always as identity primary key,
  text text not null unique check (char_length(text) between 3 and 160 and text = btrim(text)),
  published boolean not null default true,
  sort integer not null default 0,
  created_at timestamptz not null default now()
);

alter table ride_quote enable row level security;
revoke all on ride_quote from anon, authenticated;

